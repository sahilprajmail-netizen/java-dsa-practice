// STR1. Take a String of your full name. Print its length, the first character, and the last character using .charAt().
public class STR1 {
    public static void main(String[] args) {
        String name = "Sahil Prajapati";
        System.out.println(name.length());
        System.out.println(name.charAt(0));
        System.out.println(name.charAt(name.length()-1));


    }
}
